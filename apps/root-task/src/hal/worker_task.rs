impl TargetWorkerSlot {
    fn new(
        role: WorkerRole,
        admission: ExecutableRoleAdmission,
        slots: [seL4_CPtr; ROOT_SLOT_COUNT],
    ) -> Result<Self, WorkerSupervisorError> {
        if admission.executable_slots != 1
            || admission.per_slot.tcbs != 1
            || admission.per_slot.cnodes != 1
            || admission.per_slot.vspaces != 1
            || admission.per_slot.page_tables as usize != TRANSLATION_SLOT_COUNT
            || admission.per_slot.frames as usize != FRAME_COUNT
            || admission.per_slot.notifications != 1
            || admission.per_slot.endpoints != 0
            || admission.per_slot.reply_objects != 0
            || admission.per_slot.scheduling_contexts != 1
            || admission.per_slot.cspace_slots as usize != ROOT_SLOT_COUNT
            || !admission.per_slot.untyped_bytes.is_power_of_two()
        {
            return Err(WorkerSupervisorError::NotEnabled);
        }
        let translation_slots: [seL4_CPtr; TRANSLATION_SLOT_COUNT] = slots
            [TRANSLATION_SLOT_START..TRANSLATION_SLOT_START + TRANSLATION_SLOT_COUNT]
            .try_into()
            .map_err(|_| WorkerSupervisorError::NotEnabled)?;
        let anchor_bits = u8::try_from(admission.per_slot.untyped_bytes.trailing_zeros())
            .map_err(|_| WorkerSupervisorError::NotEnabled)?;
        let (role_label, task_id) = role_contract(role);
        if admission.role != role_label || admission.task_prefix != task_prefix(role) {
            return Err(WorkerSupervisorError::NotEnabled);
        }
        Ok(Self {
            role,
            role_label,
            task_id,
            anchor: seL4_CPtr::from(admission.revoke_anchor_slot),
            anchor_bits,
            anchor_created: false,
            slots,
            tracker: RevokeAnchorVSpaceTracker::new(translation_slots)
                .map_err(|_| WorkerSupervisorError::NotEnabled)?,
            scratch_vaddrs: [0; FRAME_COUNT],
            identity: None,
            resource_identity: None,
            registered_identity: None,
            contract: None,
            root_shared_frame: None,
            mapped_child: [false; FRAME_COUNT],
            tcb_created: false,
            sc_bound: false,
            admitted: false,
            resume_pending: false,
            resumed: false,
            reservation_live: false,
            standard_fault_minted: false,
            timeout_fault_minted: false,
            image_sha256: [0; 32],
            image_mapped: false,
            standard_fault_badge: 0,
            timeout_fault_badge: 0,
        })
    }

    fn validate_handle(&self, bundle: TargetWorkerBundle) -> Result<(), WorkerSupervisorError> {
        if usize::from(bundle.role_index) >= ROLE_COUNT
            || self
                .identity
                .is_none_or(|identity| identity.cap_generation != bundle.cap_generation)
        {
            return Err(WorkerSupervisorError::InvalidGeneration);
        }
        Ok(())
    }

    fn clear_generation(&mut self) {
        self.identity = None;
        self.resource_identity = None;
        self.contract = None;
        self.root_shared_frame = None;
        self.mapped_child = [false; FRAME_COUNT];
        self.tcb_created = false;
        self.sc_bound = false;
        self.admitted = false;
        self.resume_pending = false;
        self.resumed = false;
        self.reservation_live = false;
        self.standard_fault_minted = false;
        self.timeout_fault_minted = false;
        self.image_sha256 = [0; 32];
        self.image_mapped = false;
        self.standard_fault_badge = 0;
        self.timeout_fault_badge = 0;
    }
}

