/// Public Worker identifiers are generated by NineDoor and remain bounded by
/// its existing namespace grammar.
pub const TARGET_WORKER_PUBLIC_ID_BYTES: usize = 32;

/// Root-readable target projection for one compiler-admitted executable role.
///
/// This record contains no CPtrs or signal badges. It is updated only after an
/// exact supervisor transition and lets NineDoor project lifecycle truth
/// without gaining HAL or child-object authority.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct TargetWorkerNamespaceSnapshot {
    /// Exact executable role.
    pub role: WorkerRole,
    /// Current public lifecycle state.
    pub lifecycle: WorkerLifecycleState,
    /// Current or retained terminal five-part identity.
    pub identity: Option<WorkerIdentity>,
    /// Last durable READY sequence.
    pub ready_sequence: u64,
    /// Current in-flight control sequence.
    pub control_sequence: u64,
    /// Last accepted control sequence for stale/replay rejection.
    pub last_control_sequence: u64,
    /// Last correlated provider receipt sequence.
    pub receipt_sequence: u64,
    /// Last accepted durable completion sequence.
    pub completion_sequence: u64,
    /// Monotonic projection revision for change detection.
    pub revision: u64,
    public_id: [u8; TARGET_WORKER_PUBLIC_ID_BYTES],
    public_id_len: u8,
}

impl TargetWorkerNamespaceSnapshot {
    const fn empty(role: WorkerRole) -> Self {
        Self {
            role,
            lifecycle: WorkerLifecycleState::Absent,
            identity: None,
            ready_sequence: 0,
            control_sequence: 0,
            last_control_sequence: 0,
            receipt_sequence: 0,
            completion_sequence: 0,
            revision: 0,
            public_id: [0; TARGET_WORKER_PUBLIC_ID_BYTES],
            public_id_len: 0,
        }
    }

    /// Return the root-generated public Worker id, when one is reserved.
    #[must_use]
    pub fn public_id(&self) -> Option<&str> {
        let len = usize::from(self.public_id_len);
        (len != 0)
            .then(|| str::from_utf8(&self.public_id[..len]).ok())
            .flatten()
    }

    fn set_public_id(&mut self, public_id: &str) -> Result<(), WorkerSupervisorError> {
        if public_id.is_empty()
            || public_id.len() > TARGET_WORKER_PUBLIC_ID_BYTES
            || !public_id
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-')
        {
            return Err(WorkerSupervisorError::InvalidRecord);
        }
        self.public_id.fill(0);
        self.public_id[..public_id.len()].copy_from_slice(public_id.as_bytes());
        self.public_id_len =
            u8::try_from(public_id.len()).map_err(|_| WorkerSupervisorError::InvalidRecord)?;
        Ok(())
    }
}

