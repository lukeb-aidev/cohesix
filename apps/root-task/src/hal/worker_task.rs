#[derive(Clone, Copy)]
struct TargetWorkerProjection {
    armed: bool,
    control_sequence: u64,
    max_supervisor_generation: u64,
    pending_controls: [Option<WorkerControlRecord>; ROLE_COUNT],
    slots: [TargetWorkerProjectionSlot; ROLE_COUNT],
}

impl TargetWorkerProjection {
    const fn empty() -> Self {
        Self {
            armed: false,
            control_sequence: 0,
            max_supervisor_generation: 0,
            pending_controls: [None; ROLE_COUNT],
            slots: [
                TargetWorkerProjectionSlot::empty(WorkerRole::Heartbeat),
                TargetWorkerProjectionSlot::empty(WorkerRole::Gpu),
                TargetWorkerProjectionSlot::empty(WorkerRole::Lora),
            ],
        }
    }

    fn next_control_sequence(&mut self) -> Result<u64, WorkerSupervisorError> {
        self.control_sequence = self
            .control_sequence
            .checked_add(1)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
        Ok(self.control_sequence)
    }

    fn reserve_spawn(
        &mut self,
        role: WorkerRole,
        public_id: &str,
    ) -> Result<CriticalWorkerControlRecord, WorkerSupervisorError> {
        if !self.armed {
            return Err(WorkerSupervisorError::InvalidState);
        }
        let index = role_index(role);
        let lifecycle = self.slots[index].namespace.lifecycle;
        if !matches!(
            lifecycle,
            WorkerLifecycleState::Absent | WorkerLifecycleState::Terminal
        ) {
            return Err(WorkerSupervisorError::SlotBusy);
        }
        if self
            .slots
            .iter()
            .any(|slot| slot.namespace.public_id() == Some(public_id))
        {
            return Err(WorkerSupervisorError::InvalidRecord);
        }
        let identity = if lifecycle == WorkerLifecycleState::Absent {
            self.slots[index]
                .prepared_identity
                .ok_or(WorkerSupervisorError::InvalidState)?
        } else {
            let prior = self.slots[index]
                .namespace
                .identity
                .ok_or(WorkerSupervisorError::InvalidGeneration)?;
            self.max_supervisor_generation = self
                .max_supervisor_generation
                .checked_add(1)
                .ok_or(WorkerSupervisorError::InvalidGeneration)?;
            WorkerIdentity::new(
                role,
                0,
                prior
                    .lease_epoch
                    .checked_add(1)
                    .ok_or(WorkerSupervisorError::InvalidGeneration)?,
                self.max_supervisor_generation,
                prior
                    .cap_generation
                    .checked_add(1)
                    .ok_or(WorkerSupervisorError::InvalidGeneration)?,
            )
        };
        identity
            .validate_for_role(role)
            .map_err(|_| WorkerSupervisorError::InvalidGeneration)?;
        self.slots[index].namespace.set_public_id(public_id)?;
        self.slots[index].namespace.lifecycle = WorkerLifecycleState::Queued;
        self.slots[index].namespace.identity = Some(identity);
        self.slots[index].namespace.ready_sequence = 0;
        self.slots[index].namespace.control_sequence = 0;
        self.slots[index].namespace.last_control_sequence = 0;
        self.slots[index].namespace.receipt_sequence = 0;
        self.slots[index].namespace.completion_sequence = 0;
        self.slots[index].namespace.revision = self.slots[index]
            .namespace
            .revision
            .checked_add(1)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
        self.slots[index].prepared_identity = Some(identity);
        self.slots[index].runtime_init = None;
        self.slots[index].claimed = true;
        Ok(CriticalWorkerControlRecord {
            sequence: self.next_control_sequence()?,
            task_index: worker_task_index(role)?,
            identity: fault_identity(index, identity)?,
            operation: WorkerControlOperation::Admit,
        })
    }

    fn reserve_kill(
        &mut self,
        public_id: &str,
    ) -> Result<Option<CriticalWorkerControlRecord>, WorkerSupervisorError> {
        if !self.armed {
            return Err(WorkerSupervisorError::InvalidState);
        }
        let index = self
            .slots
            .iter()
            .position(|slot| slot.namespace.public_id() == Some(public_id))
            .ok_or(WorkerSupervisorError::InvalidRecord)?;
        let slot = &mut self.slots[index];
        if slot.namespace.lifecycle == WorkerLifecycleState::Closing {
            return Ok(None);
        }
        if !matches!(
            slot.namespace.lifecycle,
            WorkerLifecycleState::Queued
                | WorkerLifecycleState::Starting
                | WorkerLifecycleState::Ready
        ) {
            return Err(WorkerSupervisorError::InvalidState);
        }
        let lifecycle = slot.namespace.lifecycle;
        let identity = slot
            .namespace
            .identity
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
        slot.namespace.lifecycle = WorkerLifecycleState::Closing;
        slot.namespace.control_sequence = 0;
        slot.namespace.receipt_sequence = 0;
        slot.namespace.revision = slot
            .namespace
            .revision
            .checked_add(1)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
        self.pending_controls[index] = None;
        let role = role_from_index(index)?;
        Ok(Some(CriticalWorkerControlRecord {
            sequence: self.next_control_sequence()?,
            task_index: worker_task_index(role)?,
            identity: fault_identity(index, identity)?,
            operation: if lifecycle == WorkerLifecycleState::Queued {
                WorkerControlOperation::Revoke
            } else {
                WorkerControlOperation::Shutdown
            },
        }))
    }

    fn reserve_worker_control(
        &mut self,
        control: WorkerControlRecord,
    ) -> Result<(), WorkerSupervisorError> {
        if !self.armed || control.sequence == 0 || control.committed_sequence != control.sequence {
            return Err(WorkerSupervisorError::InvalidRecord);
        }
        let role = control
            .identity
            .worker_role()
            .map_err(|_| WorkerSupervisorError::RoleNotExecutable)?;
        let index = role_index(role);
        let slot = &mut self.slots[index];
        if !slot.claimed
            || slot.namespace.lifecycle != WorkerLifecycleState::Ready
            || slot.namespace.identity != Some(control.identity)
        {
            return Err(WorkerSupervisorError::InvalidGeneration);
        }
        if self.pending_controls[index].is_some() || slot.namespace.control_sequence != 0 {
            return Err(WorkerSupervisorError::ControlBusy);
        }
        if control.sequence <= slot.namespace.last_control_sequence {
            return Err(WorkerSupervisorError::InvalidRecord);
        }
        control.validate_for(
            slot.runtime_init
                .ok_or(WorkerSupervisorError::InvalidState)?,
        )?;
        self.pending_controls[index] = Some(control);
        slot.namespace.control_sequence = control.sequence;
        slot.namespace.last_control_sequence = control.sequence;
        slot.namespace.receipt_sequence = 0;
        slot.namespace.revision = slot
            .namespace
            .revision
            .checked_add(1)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
        Ok(())
    }
}

static TARGET_WORKER_PROJECTION: Mutex<TargetWorkerProjection> =
    Mutex::new(TargetWorkerProjection::empty());
static TARGET_WORKER_SIGNAL_CAP: AtomicUsize = AtomicUsize::new(0);

/// Return the bounded current namespace projection for all executable roles.
#[must_use]
pub fn target_worker_namespace_snapshots() -> [TargetWorkerNamespaceSnapshot; ROLE_COUNT] {
    let projection = TARGET_WORKER_PROJECTION.lock();
    projection.slots.map(|slot| slot.namespace)
}

/// Admit one existing Queen spawn request to the bounded critical handoff.
///
/// Success means only that the exact request was published and the public id
/// was reserved. The target child remains unpublished until a durable READY
/// record advances the projection.
pub fn enqueue_target_worker_spawn(
    role: WorkerRole,
    public_id: &str,
) -> Result<TargetWorkerNamespaceSnapshot, WorkerSupervisorError> {
    let mut projection = TARGET_WORKER_PROJECTION.lock();
    let before = *projection;
    let record = match projection.reserve_spawn(role, public_id) {
        Ok(record) => record,
        Err(error) => {
            *projection = before;
            return Err(error);
        }
    };
    if publish_target_worker_control(record) != PublishResult::Published {
        *projection = before;
        return Err(WorkerSupervisorError::ControlBusy);
    }
    Ok(projection.slots[role_index(role)].namespace)
}

/// Close authority for one public Worker id and enqueue bounded shutdown.
///
/// Repeating a kill while the same exact generation is already closing is
/// idempotent and does not consume another queue slot.
pub fn enqueue_target_worker_kill(
    public_id: &str,
) -> Result<TargetWorkerNamespaceSnapshot, WorkerSupervisorError> {
    let mut projection = TARGET_WORKER_PROJECTION.lock();
    let before = *projection;
    let index = projection
        .slots
        .iter()
        .position(|slot| slot.namespace.public_id() == Some(public_id))
        .ok_or(WorkerSupervisorError::InvalidRecord)?;
    let record = match projection.reserve_kill(public_id) {
        Ok(record) => record,
        Err(error) => {
            *projection = before;
            return Err(error);
        }
    };
    if let Some(record) = record {
        if publish_target_worker_control(record) != PublishResult::Published {
            *projection = before;
            return Err(WorkerSupervisorError::ControlBusy);
        }
    }
    Ok(projection.slots[index].namespace)
}

/// Queue one already root-validated GPU or PEFT result for the exact READY
/// Worker generation. The fixed Worker ABI validator remains authoritative
/// when root-control drains this one-in-flight seam into the shared page.
pub fn enqueue_target_worker_operation(
    control: WorkerControlRecord,
) -> Result<TargetWorkerNamespaceSnapshot, WorkerSupervisorError> {
    let role = control
        .identity
        .worker_role()
        .map_err(|_| WorkerSupervisorError::RoleNotExecutable)?;
    let mut projection = TARGET_WORKER_PROJECTION.lock();
    let before = *projection;
    if let Err(error) = projection.reserve_worker_control(control) {
        *projection = before;
        return Err(error);
    }
    Ok(projection.slots[role_index(role)].namespace)
}

fn publish_target_worker_control(record: CriticalWorkerControlRecord) -> PublishResult {
    let signal_cap = TARGET_WORKER_SIGNAL_CAP.load(Ordering::Acquire) as seL4_CPtr;
    super::critical_tcb::publish_worker_control(record, signal_cap)
}

fn install_target_worker_projection(
    supervisor: &WorkerSupervisor<TargetWorkerBackend>,
    worker_signal_cap: seL4_CPtr,
) -> Result<(), WorkerSupervisorError> {
    if worker_signal_cap == sel4_sys::seL4_CapNull {
        return Err(WorkerSupervisorError::InvalidState);
    }
    let mut projection = TargetWorkerProjection::empty();
    for role in [WorkerRole::Heartbeat, WorkerRole::Gpu, WorkerRole::Lora] {
        let identity = supervisor
            .snapshot(role)?
            .identity
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
        let slot = &mut projection.slots[role_index(role)];
        slot.prepared_identity = Some(identity);
        slot.runtime_init = Some(supervisor.runtime_init(role)?);
        projection.max_supervisor_generation = projection
            .max_supervisor_generation
            .max(identity.supervisor_generation);
    }
    *TARGET_WORKER_PROJECTION.lock() = projection;
    TARGET_WORKER_SIGNAL_CAP.store(worker_signal_cap as usize, Ordering::Release);
    Ok(())
}

fn arm_target_worker_projection() -> Result<(), WorkerSupervisorError> {
    let mut projection = TARGET_WORKER_PROJECTION.lock();
    if projection.armed
        || projection
            .slots
            .iter()
            .any(|slot| slot.prepared_identity.is_none() || slot.claimed)
    {
        return Err(WorkerSupervisorError::InvalidState);
    }
    projection.armed = true;
    Ok(())
}

fn target_worker_claimed(role: WorkerRole) -> bool {
    TARGET_WORKER_PROJECTION.lock().slots[role_index(role)].claimed
}

fn target_worker_projection_snapshot(role: WorkerRole) -> TargetWorkerNamespaceSnapshot {
    TARGET_WORKER_PROJECTION.lock().slots[role_index(role)].namespace
}

fn target_worker_transition_allowed(
    current: WorkerLifecycleState,
    next: WorkerLifecycleState,
) -> bool {
    match current {
        WorkerLifecycleState::Absent => next == WorkerLifecycleState::Absent,
        WorkerLifecycleState::Queued => matches!(
            next,
            WorkerLifecycleState::Queued
                | WorkerLifecycleState::Starting
                | WorkerLifecycleState::Closing
                | WorkerLifecycleState::Faulted
                | WorkerLifecycleState::Terminal
        ),
        WorkerLifecycleState::Starting => matches!(
            next,
            WorkerLifecycleState::Starting
                | WorkerLifecycleState::Ready
                | WorkerLifecycleState::Closing
                | WorkerLifecycleState::Faulted
                | WorkerLifecycleState::Terminal
        ),
        WorkerLifecycleState::Ready => matches!(
            next,
            WorkerLifecycleState::Ready
                | WorkerLifecycleState::Closing
                | WorkerLifecycleState::Faulted
                | WorkerLifecycleState::Terminal
        ),
        WorkerLifecycleState::Closing => matches!(
            next,
            WorkerLifecycleState::Closing
                | WorkerLifecycleState::Faulted
                | WorkerLifecycleState::Terminal
        ),
        WorkerLifecycleState::Faulted => matches!(
            next,
            WorkerLifecycleState::Faulted | WorkerLifecycleState::Terminal
        ),
        WorkerLifecycleState::Terminal => next == WorkerLifecycleState::Terminal,
    }
}

fn update_target_worker_projection(
    snapshot: crate::worker_supervisor::WorkerSlotSnapshot,
) -> Result<(), WorkerSupervisorError> {
    let index = role_index(snapshot.role);
    let mut projection = TARGET_WORKER_PROJECTION.lock();
    {
        let slot = &mut projection.slots[index];
        if !slot.claimed {
            return Err(WorkerSupervisorError::InvalidState);
        }
        if let (Some(expected), Some(observed)) = (slot.namespace.identity, snapshot.identity) {
            if expected != observed {
                return Err(WorkerSupervisorError::InvalidGeneration);
            }
        }
        if !target_worker_transition_allowed(slot.namespace.lifecycle, snapshot.lifecycle) {
            return Err(WorkerSupervisorError::InvalidState);
        }
        slot.namespace.lifecycle = snapshot.lifecycle;
        slot.namespace.identity = snapshot.identity;
        slot.namespace.ready_sequence = snapshot.ready_sequence;
        slot.namespace.control_sequence = snapshot.control_sequence;
        if snapshot.control_sequence > slot.namespace.last_control_sequence {
            slot.namespace.last_control_sequence = snapshot.control_sequence;
        }
        if snapshot.receipt_sequence != 0 {
            slot.namespace.receipt_sequence = snapshot.receipt_sequence;
        }
        slot.namespace.revision = slot
            .namespace
            .revision
            .checked_add(1)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
    }
    if matches!(snapshot.lifecycle, WorkerLifecycleState::Terminal) {
        projection.pending_controls[index] = None;
        projection.slots[index].runtime_init = None;
    }
    Ok(())
}

fn set_target_worker_runtime_init(
    role: WorkerRole,
    init: WorkerRuntimeInit,
) -> Result<(), WorkerSupervisorError> {
    init.validate_for_role(role)?;
    let mut projection = TARGET_WORKER_PROJECTION.lock();
    let slot = &mut projection.slots[role_index(role)];
    if !slot.claimed || slot.namespace.identity != Some(init.identity) {
        return Err(WorkerSupervisorError::InvalidGeneration);
    }
    slot.runtime_init = Some(init);
    Ok(())
}

fn target_worker_admit_pending(
    role: WorkerRole,
    identity: WorkerIdentity,
) -> Result<bool, WorkerSupervisorError> {
    let projection = TARGET_WORKER_PROJECTION.lock();
    let slot = &projection.slots[role_index(role)];
    if !slot.claimed || slot.namespace.identity != Some(identity) {
        return Err(WorkerSupervisorError::InvalidGeneration);
    }
    Ok(slot.namespace.lifecycle == WorkerLifecycleState::Queued)
}

fn take_target_worker_operation(role: WorkerRole) -> Option<WorkerControlRecord> {
    TARGET_WORKER_PROJECTION.lock().pending_controls[role_index(role)].take()
}

fn mark_target_worker_completion(
    role: WorkerRole,
    sequence: u64,
) -> Result<(), WorkerSupervisorError> {
    if sequence == 0 {
        return Err(WorkerSupervisorError::InvalidRecord);
    }
    let mut projection = TARGET_WORKER_PROJECTION.lock();
    let slot = &mut projection.slots[role_index(role)];
    if sequence <= slot.namespace.completion_sequence {
        return Err(WorkerSupervisorError::InvalidRecord);
    }
    slot.namespace.completion_sequence = sequence;
    slot.namespace.revision = slot
        .namespace
        .revision
        .checked_add(1)
        .ok_or(WorkerSupervisorError::InvalidGeneration)?;
    Ok(())
}

fn mark_target_worker_lifecycle(
    role: WorkerRole,
    lifecycle: WorkerLifecycleState,
) -> Result<(), WorkerSupervisorError> {
    let index = role_index(role);
    let mut projection = TARGET_WORKER_PROJECTION.lock();
    let slot = &mut projection.slots[index];
    if !slot.claimed || slot.namespace.identity.is_none() {
        return Err(WorkerSupervisorError::InvalidState);
    }
    if !target_worker_transition_allowed(slot.namespace.lifecycle, lifecycle) {
        return Err(WorkerSupervisorError::InvalidState);
    }
    slot.namespace.lifecycle = lifecycle;
    slot.namespace.revision = slot
        .namespace
        .revision
        .checked_add(1)
        .ok_or(WorkerSupervisorError::InvalidGeneration)?;
    Ok(())
}

