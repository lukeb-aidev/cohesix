fn worker_image_name(role: WorkerRole) -> &'static str {
    match role {
        WorkerRole::Heartbeat => "worker-heart",
        WorkerRole::Gpu => "worker-gpu",
        WorkerRole::Lora => "worker-lora",
    }
}

fn role_from_index(index: usize) -> Result<WorkerRole, WorkerSupervisorError> {
    match index {
        0 => Ok(WorkerRole::Heartbeat),
        1 => Ok(WorkerRole::Gpu),
        2 => Ok(WorkerRole::Lora),
        _ => Err(WorkerSupervisorError::InvalidRecord),
    }
}

fn rollback_bootstrap_workers(
    supervisor: &mut WorkerSupervisor<TargetWorkerBackend>,
    constructed: &[WorkerRole],
) -> Result<(), WorkerSupervisorError> {
    for role in constructed.iter().rev().copied() {
        supervisor
            .revoke(role)
            .map_err(|_| WorkerSupervisorError::ContainmentIncomplete)?;
    }
    worker_supervisor::clear_target_supervisor_mailbox()
}

fn read_worker_records(page: *mut WorkerSharedPage) -> StableWorkerRecords {
    // SAFETY: The pointer comes only from a live root mapping retained by the
    // target Worker backend. Each producer writes its fixed record with a zero
    // commit first and the sequence last; double-reading that aligned commit
    // around a volatile body copy rejects every torn or concurrent update.
    unsafe {
        StableWorkerRecords {
            ready: read_stable_record(
                core::ptr::addr_of!((*page).ready),
                core::ptr::addr_of!((*page).ready.committed_sequence),
            ),
            completion: read_stable_record(
                core::ptr::addr_of!((*page).completion),
                core::ptr::addr_of!((*page).completion.committed_sequence),
            ),
            gpu_receipt: read_stable_record(
                core::ptr::addr_of!((*page).gpu_receipt),
                core::ptr::addr_of!((*page).gpu_receipt.committed_sequence),
            ),
            peft_receipt: read_stable_record(
                core::ptr::addr_of!((*page).peft_receipt),
                core::ptr::addr_of!((*page).peft_receipt.committed_sequence),
            ),
        }
    }
}

unsafe fn read_stable_record<T: Copy>(record: *const T, commit: *const u64) -> Option<T> {
    // SAFETY: `read_worker_records` supplies aligned fields within one live
    // mapped WorkerSharedPage. Volatile accesses and acquire fences implement
    // the ABI's sequence-last stable-read protocol across seL4 VSpaces.
    unsafe {
        let before = core::ptr::read_volatile(commit);
        if before == 0 {
            return None;
        }
        fence(Ordering::Acquire);
        let value = core::ptr::read_volatile(record);
        fence(Ordering::Acquire);
        let after = core::ptr::read_volatile(commit);
        (before == after).then_some(value)
    }
}
