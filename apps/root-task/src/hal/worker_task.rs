/// Root-control-owned live supervisor for the three mandatory target Workers.
pub struct TargetWorkerRuntime {
    supervisor: WorkerSupervisor<TargetWorkerBackend>,
    ready_sequences: [u64; ROLE_COUNT],
    completion_sequences: [u64; ROLE_COUNT],
    receipt_sequences: [u64; ROLE_COUNT],
    last_policy_sequence: u64,
    deadline_cursor: WorkerDeadlineCursor,
}

impl TargetWorkerRuntime {
    /// Construct all three exact images while keeping their TCBs suspended
    /// until the complete fault registry and critical duties are active.
    pub fn bootstrap(
        hal: &mut KernelHal<'static>,
        critical: &'static CriticalTcbRuntime,
        now_ms: u64,
    ) -> Result<Self, WorkerSupervisorError> {
        worker_supervisor::prepare_target_supervisor_mailbox()?;
        let backend = match TargetWorkerBackend::new(hal, critical) {
            Ok(backend) => backend,
            Err(error) => {
                let _ = worker_supervisor::clear_target_supervisor_mailbox();
                return Err(error);
            }
        };
        let mut supervisor = WorkerSupervisor::new(backend);
        let roles = [WorkerRole::Heartbeat, WorkerRole::Gpu, WorkerRole::Lora];
        let mut constructed = Vec::<WorkerRole, ROLE_COUNT>::new();
        for role in roles {
            let image_name = worker_image_name(role);
            let (plan, image) = match super::worker_image::plan_embedded_worker_image(image_name) {
                Ok(planned) => planned,
                Err(_) => {
                    rollback_bootstrap_workers(&mut supervisor, &constructed)?;
                    return Err(WorkerSupervisorError::InvalidImage);
                }
            };
            if supervisor.spawn(role, 1, &plan, image, now_ms).is_err() {
                rollback_bootstrap_workers(&mut supervisor, &constructed)?;
                return Err(WorkerSupervisorError::Backend);
            }
            constructed
                .push(role)
                .map_err(|_| WorkerSupervisorError::NotEnabled)?;
        }
        if let Err(error) =
            install_target_worker_projection(&supervisor, critical.signals.worker_supervisor)
        {
            rollback_bootstrap_workers(&mut supervisor, &constructed)?;
            return Err(error);
        }
        Ok(Self {
            supervisor,
            ready_sequences: [0; ROLE_COUNT],
            completion_sequences: [0; ROLE_COUNT],
            receipt_sequences: [0; ROLE_COUNT],
            last_policy_sequence: 0,
            deadline_cursor: WorkerDeadlineCursor::default(),
        })
    }

    /// Arm the Worker supervisor after the independent fault receiver owns both
    /// generated MCS fault lanes. The three preconstructed role TCBs remain
    /// suspended until an exact Queen spawn reaches the bounded policy queue.
    pub fn activate(&mut self) -> Result<(), WorkerSupervisorError> {
        if self.supervisor.backend_mut().arm_deferred()? != ROLE_COUNT {
            return Err(WorkerSupervisorError::InvalidState);
        }
        arm_target_worker_projection()?;
        log::info!(
            "WORKER_TASK_ACTIVATION roles={} state=armed-suspended fault_receiver=active",
            ROLE_COUNT,
        );
        Ok(())
    }

    /// Drain one bounded target turn in fault, completion, policy, then
    /// generated-deadline order.
    pub fn service(&mut self, now_ms: u64) -> Result<usize, WorkerSupervisorError> {
        let mut processed = 0usize;
        while processed < TARGET_WORKER_SERVICE_BOUND {
            if let Some(work) = worker_supervisor::take_target_supervisor_work()? {
                self.handle_supervisor_work(work, now_ms)?;
                processed += 1;
                continue;
            }
            if self.handle_pending_worker_operation()? {
                processed += 1;
                continue;
            }
            break;
        }
        for role in [WorkerRole::Heartbeat, WorkerRole::Gpu, WorkerRole::Lora] {
            if target_worker_claimed(role) && self.supervisor.enforce_role_deadline(role, now_ms)? {
                update_target_worker_projection(self.supervisor.snapshot(role)?)?;
                processed = processed
                    .checked_add(1)
                    .ok_or(WorkerSupervisorError::Backend)?;
            }
        }
        Ok(processed)
    }

    /// Service one persistent isolated-VirtIO Worker unit.
    ///
    /// A mailbox record or pending Queen operation consumes the complete unit.
    /// When neither exists, exactly one retained role slot is checked for a
    /// generated deadline, with the successor committed before the check.
    pub fn service_one(&mut self, now_ms: u64) -> Result<usize, WorkerSupervisorError> {
        if let Some(work) = worker_supervisor::take_target_supervisor_work()? {
            self.handle_supervisor_work(work, now_ms)?;
            return Ok(1);
        }
        if self.handle_pending_worker_operation()? {
            return Ok(1);
        }

        let role = self.deadline_cursor.take();
        if target_worker_claimed(role) && self.supervisor.enforce_role_deadline(role, now_ms)? {
            update_target_worker_projection(self.supervisor.snapshot(role)?)?;
            return Ok(1);
        }
        Ok(0)
    }

    /// Immutable supervisor projection used by the root namespace adapter.
    #[must_use]
    pub const fn supervisor(&self) -> &WorkerSupervisor<TargetWorkerBackend> {
        &self.supervisor
    }

    /// Mutable supervisor access for already validated Queen operations.
    pub fn supervisor_mut(&mut self) -> &mut WorkerSupervisor<TargetWorkerBackend> {
        &mut self.supervisor
    }

    fn handle_supervisor_work(
        &mut self,
        work: TargetSupervisorWork,
        now_ms: u64,
    ) -> Result<(), WorkerSupervisorError> {
        match work {
            TargetSupervisorWork::Fault(record) => self.handle_fault(record),
            TargetSupervisorWork::Wake(badge) => self.handle_wake(badge),
            TargetSupervisorWork::Control(record) => self.handle_policy(record, now_ms),
        }
    }

    fn handle_pending_worker_operation(&mut self) -> Result<bool, WorkerSupervisorError> {
        for role in [WorkerRole::Heartbeat, WorkerRole::Gpu, WorkerRole::Lora] {
            let Some(control) = take_target_worker_operation(role) else {
                continue;
            };
            self.supervisor.submit_control(control)?;
            update_target_worker_projection(self.supervisor.snapshot(role)?)?;
            log::info!(
                "WORKER_TASK_CONTROL role={} slot={} lease_epoch={} supervisor_generation={} cap_generation={} action=0x{:04x} outcome={} sequence={} state=admitted",
                role_contract(role).0,
                control.identity.slot,
                control.identity.lease_epoch,
                control.identity.supervisor_generation,
                control.identity.cap_generation,
                control.action,
                control.outcome,
                control.sequence,
            );
            return Ok(true);
        }
        Ok(false)
    }

    fn handle_wake(&mut self, badge: u64) -> Result<(), WorkerSupervisorError> {
        let abi = generated::worker_runtime_config().task_abi;
        let role_bits = [
            (WorkerRole::Heartbeat, abi.heartbeat_wake_bit),
            (WorkerRole::Gpu, abi.gpu_wake_bit),
            (WorkerRole::Lora, abi.lora_wake_bit),
        ];
        if badge == 0
            || badge & !(abi.heartbeat_wake_bit | abi.gpu_wake_bit | abi.lora_wake_bit) != 0
        {
            return Err(WorkerSupervisorError::InvalidRecord);
        }
        for (role, bit) in role_bits {
            if badge & bit != 0 {
                self.handle_role_records(role)?;
            }
        }
        Ok(())
    }

    fn handle_role_records(&mut self, role: WorkerRole) -> Result<(), WorkerSupervisorError> {
        let index = role_index(role);
        let snapshot = self.supervisor.snapshot(role)?;
        let projected = target_worker_projection_snapshot(role);
        if snapshot.identity != projected.identity {
            return Err(WorkerSupervisorError::InvalidGeneration);
        }
        match snapshot.lifecycle {
            WorkerLifecycleState::Terminal => return Ok(()),
            WorkerLifecycleState::Starting
                if projected.lifecycle != WorkerLifecycleState::Starting =>
            {
                // A queued kill closes READY authority before its shutdown or
                // revoke record reaches root-control.
                return Ok(());
            }
            WorkerLifecycleState::Ready if projected.lifecycle != WorkerLifecycleState::Ready => {
                // Receipt/control completion authority closes synchronously at
                // kill admission; a stale wake is only a scheduling hint.
                return Ok(());
            }
            WorkerLifecycleState::Closing
                if projected.lifecycle != WorkerLifecycleState::Closing =>
            {
                return Err(WorkerSupervisorError::InvalidState);
            }
            WorkerLifecycleState::Absent
            | WorkerLifecycleState::Queued
            | WorkerLifecycleState::Faulted => return Err(WorkerSupervisorError::InvalidState),
            _ => {}
        }
        let pointer = self
            .supervisor
            .backend()
            .shared_page_ptr(role)
            .ok_or(WorkerSupervisorError::InvalidState)?;
        let records = read_worker_records(pointer);
        if snapshot.lifecycle == WorkerLifecycleState::Starting {
            if let Some(ready) = records.ready {
                if ready.sequence <= self.ready_sequences[index] {
                    return Err(WorkerSupervisorError::InvalidRecord);
                }
                let accepted = self.supervisor.accept_ready(ready)?;
                self.ready_sequences[index] = ready.sequence;
                update_target_worker_projection(accepted)?;
                let (role_label, _) = role_contract(role);
                log::info!(
                    "WORKER_TASK_READY role={} slot={} lease_epoch={} supervisor_generation={} cap_generation={} sequence={}",
                    role_label,
                    ready.identity.slot,
                    ready.identity.lease_epoch,
                    ready.identity.supervisor_generation,
                    ready.identity.cap_generation,
                    ready.sequence,
                );
            }
            return Ok(());
        }

        if snapshot.lifecycle == WorkerLifecycleState::Ready {
            if let Some(receipt) = records.gpu_receipt {
                if role == WorkerRole::Gpu && receipt.sequence > self.receipt_sequences[index] {
                    let accepted = self.supervisor.accept_gpu_receipt(receipt)?;
                    self.receipt_sequences[index] = receipt.sequence;
                    update_target_worker_projection(accepted)?;
                    log::info!(
                        "WORKER_TASK_RECEIPT role=worker-gpu slot={} lease_epoch={} supervisor_generation={} cap_generation={} action=0x{:04x} outcome={} sequence={}",
                        receipt.identity.slot,
                        receipt.identity.lease_epoch,
                        receipt.identity.supervisor_generation,
                        receipt.identity.cap_generation,
                        receipt.action,
                        receipt.outcome,
                        receipt.sequence,
                    );
                }
            }
            if let Some(receipt) = records.peft_receipt {
                if role == WorkerRole::Lora && receipt.sequence > self.receipt_sequences[index] {
                    let accepted = self.supervisor.accept_peft_receipt(receipt)?;
                    self.receipt_sequences[index] = receipt.sequence;
                    update_target_worker_projection(accepted)?;
                    log::info!(
                        "WORKER_TASK_RECEIPT role=worker-lora slot={} lease_epoch={} supervisor_generation={} cap_generation={} action=0x{:04x} outcome={} sequence={}",
                        receipt.identity.slot,
                        receipt.identity.lease_epoch,
                        receipt.identity.supervisor_generation,
                        receipt.identity.cap_generation,
                        receipt.action,
                        receipt.outcome,
                        receipt.sequence,
                    );
                }
            }
        }
        if let Some(completion) = records.completion {
            if completion.sequence > self.completion_sequences[index] {
                let status = WorkerCompletionStatus::from_raw(completion.status)?;
                if snapshot.lifecycle == WorkerLifecycleState::Closing
                    && matches!(
                        status,
                        WorkerCompletionStatus::Confirmed
                            | WorkerCompletionStatus::Rejected
                            | WorkerCompletionStatus::Stale
                    )
                {
                    return Ok(());
                }
                let terminal_fault = matches!(
                    status,
                    WorkerCompletionStatus::Revoked
                        | WorkerCompletionStatus::Timeout
                        | WorkerCompletionStatus::InvalidControl
                        | WorkerCompletionStatus::Panic
                );
                let accepted = match self.supervisor.accept_completion(completion) {
                    Ok(accepted) => accepted,
                    Err(error) => {
                        let contained = self.supervisor.snapshot(role)?;
                        if contained.lifecycle == WorkerLifecycleState::Terminal {
                            mark_target_worker_lifecycle(role, WorkerLifecycleState::Faulted)?;
                            update_target_worker_projection(contained)?;
                        }
                        return Err(error);
                    }
                };
                if terminal_fault {
                    mark_target_worker_lifecycle(role, WorkerLifecycleState::Faulted)?;
                    log::error!(
                        "WORKER_TASK_COMPLETION_FAULT role={} slot={} lease_epoch={} supervisor_generation={} cap_generation={} status={} state=faulted",
                        role_contract(role).0,
                        completion.identity.slot,
                        completion.identity.lease_epoch,
                        completion.identity.supervisor_generation,
                        completion.identity.cap_generation,
                        completion.status,
                    );
                }
                self.completion_sequences[index] = completion.sequence;
                update_target_worker_projection(accepted)?;
                mark_target_worker_completion(role, completion.sequence)?;
                let (role_label, _) = role_contract(role);
                log::info!(
                    "WORKER_TASK_COMPLETION role={} slot={} lease_epoch={} supervisor_generation={} cap_generation={} action=0x{:04x} status={} sequence={}",
                    role_label,
                    completion.identity.slot,
                    completion.identity.lease_epoch,
                    completion.identity.supervisor_generation,
                    completion.identity.cap_generation,
                    completion.action,
                    completion.status,
                    completion.sequence,
                );
            }
        }
        Ok(())
    }

    fn handle_fault(
        &mut self,
        record: crate::critical_tcb::FaultHandoffRecord,
    ) -> Result<(), WorkerSupervisorError> {
        let index = crate::critical_tcb::worker_fault_mailbox_index(record.task_index)
            .ok_or(WorkerSupervisorError::InvalidRecord)?;
        let role = role_from_index(index)?;
        let snapshot = self.supervisor.snapshot(role)?;
        let identity = snapshot
            .identity
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
        if target_worker_projection_snapshot(role).identity != Some(identity)
            || fault_identity(index, identity)? != record.identity
        {
            return Err(WorkerSupervisorError::InvalidGeneration);
        }
        if snapshot.lifecycle == WorkerLifecycleState::Terminal {
            log::info!(
                "WORKER_TASK_FAULT role={} slot={} lease_epoch={} supervisor_generation={} cap_generation={} state=terminal outcome=already-contained",
                role_contract(role).0,
                identity.slot,
                identity.lease_epoch,
                identity.supervisor_generation,
                identity.cap_generation,
            );
            return Ok(());
        }
        mark_target_worker_lifecycle(role, WorkerLifecycleState::Faulted)?;
        log::error!(
            "WORKER_TASK_FAULT role={} slot={} lease_epoch={} supervisor_generation={} cap_generation={} class={:?} observed_badge={} state=faulted",
            role_contract(role).0,
            identity.slot,
            identity.lease_epoch,
            identity.supervisor_generation,
            identity.cap_generation,
            record.fault_class,
            record.fault_badge,
        );
        let terminal = self
            .supervisor
            .fault(identity, record.fault_class == FaultClass::Timeout)?;
        update_target_worker_projection(terminal)?;
        Ok(())
    }

    fn handle_policy(
        &mut self,
        record: crate::critical_tcb::WorkerControlRecord,
        now_ms: u64,
    ) -> Result<(), WorkerSupervisorError> {
        if record.sequence <= self.last_policy_sequence {
            return Err(WorkerSupervisorError::InvalidRecord);
        }
        let index = crate::critical_tcb::worker_fault_mailbox_index(record.task_index)
            .ok_or(WorkerSupervisorError::InvalidRecord)?;
        let role = role_from_index(index)?;
        match record.operation {
            WorkerControlOperation::Admit => {
                let expected = worker_identity_from_fault(role, record.identity)?;
                let current = self.supervisor.snapshot(role)?;
                let identity = if current.lifecycle == WorkerLifecycleState::Starting {
                    let identity = current
                        .identity
                        .ok_or(WorkerSupervisorError::InvalidGeneration)?;
                    if identity != expected || fault_identity(index, identity)? != record.identity {
                        return Err(WorkerSupervisorError::InvalidGeneration);
                    }
                    identity
                } else if current.lifecycle == WorkerLifecycleState::Terminal {
                    let (plan, image) =
                        super::worker_image::plan_embedded_worker_image(worker_image_name(role))
                            .map_err(|_| WorkerSupervisorError::InvalidImage)?;
                    let receipt =
                        self.supervisor
                            .spawn(role, expected.lease_epoch, &plan, image, now_ms)?;
                    if receipt.identity != expected {
                        return Err(WorkerSupervisorError::InvalidGeneration);
                    }
                    receipt.identity
                } else {
                    return Err(WorkerSupervisorError::InvalidState);
                };
                set_target_worker_runtime_init(role, self.supervisor.runtime_init(role)?)?;
                if !target_worker_admit_pending(role, identity)? {
                    log::info!(
                        "WORKER_TASK_SPAWN_ADMITTED role={} slot={} lease_epoch={} supervisor_generation={} cap_generation={} state=cancelled-suspended",
                        role_contract(role).0,
                        identity.slot,
                        identity.lease_epoch,
                        identity.supervisor_generation,
                        identity.cap_generation,
                    );
                    self.last_policy_sequence = record.sequence;
                    return Ok(());
                }
                self.supervisor.backend_mut().activate_deferred_role(role)?;
                let receipt = self
                    .supervisor
                    .arm_preconstructed_ready_deadline(role, now_ms)?;
                update_target_worker_projection(self.supervisor.snapshot(role)?)?;
                log::info!(
                    "WORKER_TASK_SPAWN_ADMITTED role={} slot={} lease_epoch={} supervisor_generation={} cap_generation={} state=starting ready_deadline_ms={}",
                    role_contract(role).0,
                    receipt.identity.slot,
                    receipt.identity.lease_epoch,
                    receipt.identity.supervisor_generation,
                    receipt.identity.cap_generation,
                    receipt.ready_deadline_ms,
                );
            }
            WorkerControlOperation::Shutdown => {
                let current = self.supervisor.snapshot(role)?;
                let identity = current
                    .identity
                    .ok_or(WorkerSupervisorError::InvalidGeneration)?;
                if fault_identity(index, identity)? != record.identity {
                    return Err(WorkerSupervisorError::InvalidGeneration);
                }
                if current.lifecycle == WorkerLifecycleState::Terminal {
                    log::info!(
                        "WORKER_TASK_SHUTDOWN role={} lease_epoch={} supervisor_generation={} cap_generation={} state=terminal outcome=already-contained",
                        role_contract(role).0,
                        identity.lease_epoch,
                        identity.supervisor_generation,
                        identity.cap_generation,
                    );
                    self.last_policy_sequence = record.sequence;
                    return Ok(());
                }
                let closing = self.supervisor.begin_shutdown(role, now_ms)?;
                update_target_worker_projection(closing)?;
            }
            WorkerControlOperation::Revoke => {
                let current = self.supervisor.snapshot(role)?;
                let identity = current
                    .identity
                    .ok_or(WorkerSupervisorError::InvalidGeneration)?;
                if fault_identity(index, identity)? != record.identity {
                    return Err(WorkerSupervisorError::InvalidGeneration);
                }
                if current.lifecycle == WorkerLifecycleState::Terminal {
                    log::info!(
                        "WORKER_TASK_REVOKE role={} lease_epoch={} supervisor_generation={} cap_generation={} state=terminal outcome=already-contained",
                        role_contract(role).0,
                        identity.lease_epoch,
                        identity.supervisor_generation,
                        identity.cap_generation,
                    );
                    self.last_policy_sequence = record.sequence;
                    return Ok(());
                }
                mark_target_worker_lifecycle(role, WorkerLifecycleState::Faulted)?;
                let terminal = self.supervisor.revoke(role)?;
                update_target_worker_projection(terminal)?;
            }
        }
        self.last_policy_sequence = record.sequence;
        Ok(())
    }
}

#[derive(Clone, Copy)]
struct StableWorkerRecords {
    ready: Option<worker_task_abi::WorkerReadyRecord>,
    completion: Option<worker_task_abi::WorkerCompletionRecord>,
    gpu_receipt: Option<worker_task_abi::GpuLeaseReceiptRecord>,
    peft_receipt: Option<worker_task_abi::PeftReceiptRecord>,
}

impl TargetWorkerBackend {
    /// Reserve all fixed init-CNode destinations for three executable roles.
    pub fn new(
        hal: &mut KernelHal<'static>,
        critical: &'static CriticalTcbRuntime,
    ) -> Result<Self, WorkerSupervisorError> {
        let hal_ptr = hal as *mut KernelHal<'static> as usize;
        if hal_ptr == 0 {
            return Err(WorkerSupervisorError::Backend);
        }
        let admissions = generated::worker_resource_admission_config().executable_roles;
        let heart = admission_for(admissions, WorkerRole::Heartbeat)?;
        let gpu = admission_for(admissions, WorkerRole::Gpu)?;
        let lora = admission_for(admissions, WorkerRole::Lora)?;
        let heart_slots = allocate_root_slots(hal)?;
        let gpu_slots = allocate_root_slots(hal)?;
        let lora_slots = allocate_root_slots(hal)?;
        Ok(Self {
            hal_ptr,
            critical,
            pool: SupervisorResourcePool::from_generated()
                .map_err(|_| WorkerSupervisorError::NotEnabled)?,
            slots: [
                TargetWorkerSlot::new(WorkerRole::Heartbeat, heart, heart_slots)?,
                TargetWorkerSlot::new(WorkerRole::Gpu, gpu, gpu_slots)?,
                TargetWorkerSlot::new(WorkerRole::Lora, lora, lora_slots)?,
            ],
        })
    }

    fn hal_mut(&mut self) -> &mut KernelHal<'static> {
        // SAFETY: `kernel.rs` leaks this exact `KernelHal<'static>` for the root
        // lifetime. Only root-control calls backend methods, and no method keeps
        // a reference after returning or overlaps another HAL operation.
        unsafe { &mut *(self.hal_ptr as *mut KernelHal<'static>) }
    }

    /// Validate every initial child deferred until registry seal/critical
    /// activation without making any Worker executable.
    pub fn arm_deferred(&mut self) -> Result<usize, WorkerSupervisorError> {
        if !super::critical_tcb::target_fault_receiver_active() {
            return Err(WorkerSupervisorError::InvalidState);
        }
        Ok(self
            .slots
            .iter()
            .filter(|slot| slot.resume_pending && !slot.resumed && slot.admitted)
            .count())
    }

    /// Resume one exact preconstructed role after its Queen admission record is
    /// drained by root-control.
    pub fn activate_deferred_role(
        &mut self,
        role: WorkerRole,
    ) -> Result<(), WorkerSupervisorError> {
        if !super::critical_tcb::target_fault_receiver_active() {
            return Err(WorkerSupervisorError::InvalidState);
        }
        let slot = &mut self.slots[role_index(role)];
        if !slot.resume_pending || slot.resumed || !slot.admitted {
            return Err(WorkerSupervisorError::InvalidState);
        }
        sel4::resume_tcb(slot.slots[TCB_SLOT_INDEX]).map_err(|_| WorkerSupervisorError::Backend)?;
        slot.resume_pending = false;
        slot.resumed = true;
        Ok(())
    }

    /// Stable root mapping for one role's durable ABI page.
    #[must_use]
    pub fn shared_page_ptr(&self, role: WorkerRole) -> Option<*mut WorkerSharedPage> {
        let slot = self.slots.get(role_index(role))?;
        let frame = slot.root_shared_frame.as_ref()?;
        Some(frame.ptr().as_ptr().cast::<WorkerSharedPage>())
    }

    fn construct_objects(
        &mut self,
        index: usize,
        identity: WorkerIdentity,
        contract: WorkerChildContract,
    ) -> Result<TargetWorkerBundle, WorkerSupervisorError> {
        let resource_identity = resource_identity(identity)?;
        let anchor = self.slots[index].anchor;
        let role_label = self.slots[index].role_label;
        self.pool
            .reserve(role_label, resource_identity, anchor as usize)
            .map_err(map_pool_error)?;
        self.slots[index].reservation_live = true;
        self.slots[index].resource_identity = Some(resource_identity);
        self.slots[index].identity = Some(identity);
        self.slots[index].contract = Some(contract);

        let hal_ptr = self.hal_ptr;
        let critical = self.critical;
        let slot = &mut self.slots[index];
        // SAFETY: See `hal_mut`; this split borrow touches disjoint backend
        // fields and remains serialized on root-control.
        let hal = unsafe { &mut *(hal_ptr as *mut KernelHal<'static>) };
        if !slot.anchor_created {
            let created = hal
                .env
                .create_revoke_anchor(slot.anchor, slot.anchor_bits)
                .map_err(|_| WorkerSupervisorError::Backend)?;
            if created != slot.anchor {
                return Err(WorkerSupervisorError::Backend);
            }
            slot.anchor_created = true;
        }

        retype(
            hal,
            slot.anchor,
            slot.slots[TCB_SLOT_INDEX],
            sel4_sys::seL4_TCBObject as seL4_Word,
            0,
        )?;
        slot.tcb_created = true;
        let radix = generated::worker_runtime_config()
            .task_abi
            .child_cnode_radix_bits;
        retype(
            hal,
            slot.anchor,
            slot.slots[CNODE_SLOT_INDEX],
            sel4_sys::seL4_CapTableObject as seL4_Word,
            seL4_Word::from(radix),
        )?;
        hal.env
            .create_revoke_anchor_vspace_root(slot.anchor, slot.slots[VSPACE_SLOT_INDEX])
            .map_err(map_vspace_error)?;
        let temporal = temporal_for(slot.role)?;
        retype(
            hal,
            slot.anchor,
            slot.slots[SC_SLOT_INDEX],
            sel4_sys::seL4_SchedContextObject as seL4_Word,
            seL4_Word::from(temporal.scheduling_context_bits),
        )?;
        retype(
            hal,
            slot.anchor,
            slot.slots[LIFECYCLE_NOTIFICATION_SLOT_INDEX],
            sel4_sys::seL4_NotificationObject as seL4_Word,
            sel4_sys::seL4_NotificationBits as seL4_Word,
        )?;
        for frame_index in 0..FRAME_COUNT {
            retype(
                hal,
                slot.anchor,
                slot.slots[FRAME_SLOT_START + frame_index],
                sel4_sys::seL4_ARM_SmallPageObject as seL4_Word,
                sel4::PAGE_BITS as seL4_Word,
            )?;
        }

        install_notification_caps(hal, critical, slot, contract)?;
        install_fault_caps(hal, critical, slot)?;
        Ok(TargetWorkerBundle {
            role_index: u8::try_from(index).map_err(|_| WorkerSupervisorError::Backend)?,
            cap_generation: identity.cap_generation,
        })
    }

    fn rollback_partial(&mut self, index: usize) -> Result<(), WorkerSupervisorError> {
        let hal_ptr = self.hal_ptr;
        let slot = &mut self.slots[index];
        // SAFETY: See `hal_mut`; rollback is a root-control-only operation.
        let hal = unsafe { &mut *(hal_ptr as *mut KernelHal<'static>) };
        if slot.tcb_created {
            let _ = sel4::suspend_tcb(slot.slots[TCB_SLOT_INDEX]);
        }
        delete_external_fault_caps(hal, slot, false)?;
        if slot.anchor_created {
            hal.env
                .revoke_anchor_descendants_and_reset_vspace(slot.anchor, &mut slot.tracker)
                .map_err(map_vspace_error)?;
        }
        self.release_reservation(index)?;
        self.slots[index].clear_generation();
        Ok(())
    }

    fn release_reservation(&mut self, index: usize) -> Result<(), WorkerSupervisorError> {
        let slot = &mut self.slots[index];
        if !slot.reservation_live {
            return Ok(());
        }
        let identity = slot
            .resource_identity
            .ok_or(WorkerSupervisorError::ContainmentIncomplete)?;
        self.pool
            .close_admission(identity)
            .map_err(map_pool_error)?;
        self.pool
            .mark_descendants_revoked(identity)
            .map_err(map_pool_error)?;
        self.pool
            .mark_mappings_cleared(identity)
            .map_err(map_pool_error)?;
        self.pool.release(identity).map_err(map_pool_error)?;
        slot.reservation_live = false;
        Ok(())
    }
}

impl WorkerKernelBackend for TargetWorkerBackend {
    type Bundle = TargetWorkerBundle;

    fn allocate(
        &mut self,
        identity: WorkerIdentity,
        contract: WorkerChildContract,
    ) -> Result<Self::Bundle, WorkerSupervisorError> {
        let role = identity
            .worker_role()
            .map_err(|_| WorkerSupervisorError::InvalidGeneration)?;
        let index = role_index(role);
        if self.slots[index].identity.is_some() || identity.slot != 0 {
            return Err(WorkerSupervisorError::SlotBusy);
        }
        match self.construct_objects(index, identity, contract) {
            Ok(bundle) => Ok(bundle),
            Err(error) => {
                self.rollback_partial(index)
                    .map_err(|_| WorkerSupervisorError::ContainmentIncomplete)?;
                Err(error)
            }
        }
    }

    fn map_image(
        &mut self,
        bundle: Self::Bundle,
        plan: &WorkerImagePlan,
        image: &[u8],
    ) -> Result<(), WorkerSupervisorError> {
        let index = usize::from(bundle.role_index);
        self.slots
            .get(index)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?
            .validate_handle(bundle)?;
        if plan.expected.role != self.slots[index].role_label {
            return Err(WorkerSupervisorError::InvalidImage);
        }
        let hal_ptr = self.hal_ptr;
        let slot = &mut self.slots[index];
        // SAFETY: See `hal_mut`; image mapping is serialized on root-control.
        let hal = unsafe { &mut *(hal_ptr as *mut KernelHal<'static>) };
        map_image_pages(hal, slot, plan, image)?;
        slot.image_sha256 = plan.image_sha256;
        slot.image_mapped = true;
        Ok(())
    }

    fn configure(
        &mut self,
        bundle: Self::Bundle,
        init: WorkerRuntimeInit,
        entry_vaddr: u64,
    ) -> Result<(), WorkerSupervisorError> {
        let index = usize::from(bundle.role_index);
        self.slots
            .get(index)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?
            .validate_handle(bundle)?;
        if self.slots[index].identity != Some(init.identity) {
            return Err(WorkerSupervisorError::InvalidRecord);
        }
        let hal_ptr = self.hal_ptr;
        let slot = &mut self.slots[index];
        // SAFETY: See `hal_mut`; configuration is serialized on root-control.
        let hal = unsafe { &mut *(hal_ptr as *mut KernelHal<'static>) };
        map_runtime_pages(hal, slot, init)?;
        configure_tcb(hal, slot, entry_vaddr, init)
    }

    fn admit(
        &mut self,
        bundle: Self::Bundle,
        temporal: TemporalTaskConfig,
    ) -> Result<(), WorkerSupervisorError> {
        let index = usize::from(bundle.role_index);
        self.slots
            .get(index)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?
            .validate_handle(bundle)?;
        if temporal != temporal_for(self.slots[index].role)? {
            return Err(WorkerSupervisorError::NotEnabled);
        }
        let admission = admission_for(
            generated::worker_resource_admission_config().executable_roles,
            self.slots[index].role,
        )?;
        let hal_ptr = self.hal_ptr;
        let slot = &mut self.slots[index];
        // SAFETY: See `hal_mut`; MCS admission is serialized on root-control.
        let hal = unsafe { &mut *(hal_ptr as *mut KernelHal<'static>) };
        admit_mcs(hal, slot, temporal)?;

        let worker_identity = slot
            .identity
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
        let registration = fault_identity(index, worker_identity)?;
        if let Some(prior) = slot.registered_identity {
            super::critical_tcb::replace_target_fault_source(
                slot.task_id,
                prior,
                slot.slots[TCB_SLOT_INDEX],
                registration,
            )
            .map_err(|_| WorkerSupervisorError::Backend)?;
        } else {
            super::critical_tcb::register_target_fault_source(
                slot.task_id,
                slot.slots[TCB_SLOT_INDEX],
                registration,
            )
            .map_err(|_| WorkerSupervisorError::Backend)?;
        }
        slot.registered_identity = Some(registration);
        slot.admitted = true;
        if !slot.image_mapped
            || slot.image_sha256 == [0; 32]
            || slot.standard_fault_badge == 0
            || slot.timeout_fault_badge == 0
        {
            return Err(WorkerSupervisorError::InvalidState);
        }
        let endpoint_badge = root_admitted_endpoint_badge(slot.role, worker_identity.lease_epoch)?;
        let objects = admission.per_slot;
        log::info!(
            "WORKER_TASK_ADMISSION role={} slot={} lease_epoch={} supervisor_generation={} cap_generation={} image_sha256={} endpoint_badge={} fault_badge={} core={} sc_budget_us={} sc_period_us={} tcbs={} cnodes={} vspaces={} page_tables={} asids={} frames={} endpoints={} notifications={} fault_caps={} timeout_fault_caps={} reply_objects={} scheduling_contexts={} cspace_slots={} untyped_bytes={} state=admitted",
            slot.role_label,
            worker_identity.slot,
            worker_identity.lease_epoch,
            worker_identity.supervisor_generation,
            worker_identity.cap_generation,
            EvidenceSha256(slot.image_sha256),
            endpoint_badge,
            slot.standard_fault_badge,
            admission.core,
            temporal.budget_us,
            temporal.period_us,
            objects.tcbs,
            objects.cnodes,
            objects.vspaces,
            objects.page_tables,
            objects.asids,
            objects.frames,
            objects.endpoints,
            objects.notifications,
            objects.fault_caps,
            objects.timeout_fault_caps,
            objects.reply_objects,
            objects.scheduling_contexts,
            objects.cspace_slots,
            objects.untyped_bytes,
        );
        Ok(())
    }

    fn resume(&mut self, bundle: Self::Bundle) -> Result<(), WorkerSupervisorError> {
        let index = usize::from(bundle.role_index);
        self.slots
            .get(index)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?
            .validate_handle(bundle)?;
        let slot = &mut self.slots[index];
        if !slot.admitted || slot.resumed || slot.resume_pending {
            return Err(WorkerSupervisorError::InvalidState);
        }
        // Construction never grants executable authority. Root-control resumes
        // this exact generation only after its bounded Admit remains live.
        slot.resume_pending = true;
        Ok(())
    }

    fn publish_control(
        &mut self,
        bundle: Self::Bundle,
        control: WorkerControlRecord,
        control_bit: u64,
    ) -> Result<(), WorkerSupervisorError> {
        let index = usize::from(bundle.role_index);
        let slot = self
            .slots
            .get_mut(index)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
        slot.validate_handle(bundle)?;
        let init = shared_init(slot)?;
        control.validate_for(init)?;
        let page = shared_page_ptr(slot)?;
        let mut staged = control;
        staged.committed_sequence = 0;
        // SAFETY: Root is the sole control producer and the retained root
        // mapping covers one aligned WorkerSharedPage for this live generation.
        unsafe {
            core::ptr::write_volatile(core::ptr::addr_of_mut!((*page).control), staged);
            fence(Ordering::Release);
            core::ptr::write_volatile(
                core::ptr::addr_of_mut!((*page).control.committed_sequence),
                control.sequence,
            );
        }
        signal_lifecycle_cap(slot, control_bit)
    }

    fn signal_lifecycle(
        &mut self,
        bundle: Self::Bundle,
        badge: u64,
    ) -> Result<(), WorkerSupervisorError> {
        let index = usize::from(bundle.role_index);
        let slot = self
            .slots
            .get_mut(index)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?;
        slot.validate_handle(bundle)?;
        signal_lifecycle_cap(slot, badge)
    }

    fn contain(
        &mut self,
        bundle: Self::Bundle,
        identity: WorkerIdentity,
        reason: WorkerTerminalReason,
    ) -> Result<WorkerContainmentProof, WorkerSupervisorError> {
        let index = usize::from(bundle.role_index);
        self.slots
            .get(index)
            .ok_or(WorkerSupervisorError::InvalidGeneration)?
            .validate_handle(bundle)?;
        if self.slots[index].identity != Some(identity) {
            return Err(WorkerSupervisorError::InvalidGeneration);
        }
        let proof = contain_generation(self, index)?;
        log::info!(
            "WORKER_TASK_TEARDOWN role={} slot={} lease_epoch={} supervisor_generation={} cap_generation={} reason={} tcb_suspended={} records_cleared={} scheduling_context_unbound={} mappings_scrubbed={} descendants_revoked={} objects_deleted={} generation_fenced={} state=terminal",
            role_contract(identity.worker_role().map_err(|_| WorkerSupervisorError::InvalidGeneration)?).0,
            identity.slot,
            identity.lease_epoch,
            identity.supervisor_generation,
            identity.cap_generation,
            terminal_reason_label(reason),
            yes_no(proof.tcb_suspended),
            yes_no(proof.records_cleared),
            yes_no(proof.scheduling_context_unbound),
            yes_no(proof.mappings_scrubbed),
            yes_no(proof.descendants_revoked),
            yes_no(proof.objects_deleted),
            yes_no(proof.generation_fenced),
        );
        Ok(proof)
    }
}

fn allocate_root_slots(
    hal: &mut KernelHal<'_>,
) -> Result<[seL4_CPtr; ROOT_SLOT_COUNT], WorkerSupervisorError> {
    let mut slots = [sel4_sys::seL4_CapNull; ROOT_SLOT_COUNT];
    for slot in &mut slots {
        *slot = hal
            .env
            .try_allocate_slot()
            .map_err(|_| WorkerSupervisorError::Backend)?;
    }
    Ok(slots)
}

fn admission_for(
    admissions: &[ExecutableRoleAdmission],
    role: WorkerRole,
) -> Result<ExecutableRoleAdmission, WorkerSupervisorError> {
    let label = role_contract(role).0;
    admissions
        .iter()
        .find(|entry| entry.role == label)
        .copied()
        .ok_or(WorkerSupervisorError::NotEnabled)
}

/// Derive the compiler-admitted maximum object budget for the fixed graph plus
/// the maximum three-role Worker mix.
///
/// This is an admission bound, not an observed census of kernel allocations.
pub fn target_evidence_admitted_maximum() -> Result<KernelObjectBudget, WorkerSupervisorError> {
    let config = generated::worker_resource_admission_config();
    if !config.enabled || config.executable_roles.len() != ROLE_COUNT {
        return Err(WorkerSupervisorError::NotEnabled);
    }
    let mut total = config.fixed_objects;
    for admission in config.executable_roles {
        if admission.executable_slots != 1 {
            return Err(WorkerSupervisorError::NotEnabled);
        }
        total = checked_add_budget(total, admission.per_slot)?;
    }
    Ok(total)
}

