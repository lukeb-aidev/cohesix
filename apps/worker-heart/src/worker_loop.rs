/// Badged endpoint invocation modeled by the worker loop.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct EndpointInvocation {
    /// Endpoint cap being invoked.
    pub endpoint: EndpointCap,
    /// Badge expected by the receiver for this invocation.
    pub badge: WorkerBadge,
    /// Worker-local emission sequence.
    pub sequence: u64,
    /// Invocation payload.
    pub kind: InvocationKind,
}

/// Progress classification for a single bounded worker turn.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WorkerProgress {
    /// Attach completed.
    Attached,
    /// A telemetry or receipt payload was emitted.
    Emitted,
    /// A lifecycle event was emitted.
    Lifecycle,
    /// The turn completed without output.
    Idle,
    /// The turn moved the worker into a terminal state.
    Terminal,
}

/// Result of one bounded worker turn.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StepOutcome {
    /// Bounded progress made by this turn.
    pub progress: WorkerProgress,
    /// Optional endpoint invocation emitted by this turn.
    pub output: Option<EndpointInvocation>,
}

/// Summary returned by bounded multi-turn execution.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BoundedRun {
    /// Number of events processed.
    pub processed: usize,
    /// Number of endpoint invocations emitted.
    pub emitted: usize,
    /// True when the loop ended in a terminal worker state.
    pub terminal: bool,
    /// First error encountered, if any.
    pub error: Option<WorkerLoopError>,
}

/// Errors returned by the worker loop.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WorkerLoopError {
    /// A generation-bearing Worker identity contained a zero component.
    InvalidIdentity,
    /// Endpoint CPtr was zero.
    InvalidEndpointCap,
    /// Endpoint badge was zero.
    InvalidBadge,
    /// Endpoint badge did not match the worker identity.
    BadgeMismatch,
    /// Lease TTL was zero.
    InvalidLease,
    /// Lease expiry overflowed the monotonic clock.
    LeaseOverflow,
    /// Heartbeat interval was zero.
    InvalidHeartbeatInterval,
    /// Worker role did not match the requested loop mode.
    RoleMismatch,
    /// Event requires an attached endpoint.
    NotAttached,
    /// Attach was attempted after endpoint authority already existed.
    AlreadyAttached,
    /// Event was attempted after the worker reached a terminal state.
    TerminalState,
    /// Receipt kind does not match this worker loop.
    ReceiptMismatch,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct LeaseWindow {
    expires_at_ms: u64,
}

impl LeaseWindow {
    fn new(now_ms: u64, ttl_ms: u64) -> Result<Self, WorkerLoopError> {
        if ttl_ms == 0 {
            return Err(WorkerLoopError::InvalidLease);
        }
        let expires_at_ms = now_ms
            .checked_add(ttl_ms)
            .ok_or(WorkerLoopError::LeaseOverflow)?;
        Ok(Self { expires_at_ms })
    }

    fn is_expired(self, now_ms: u64) -> bool {
        now_ms >= self.expires_at_ms
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum WorkerMode {
    Heartbeat {
        interval_ms: u64,
        next_due_ms: u64,
        tick: u64,
    },
    Receipt {
        kind: ReceiptKind,
    },
}

impl WorkerMode {
    fn receipt_kind(self) -> Option<ReceiptKind> {
        match self {
            Self::Heartbeat { .. } => Some(ReceiptKind::Heartbeat),
            Self::Receipt { kind } => Some(kind),
        }
    }
}

/// Allocation-free worker-loop state machine.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkerLoop {
    identity: WorkerIdentity,
    state: WorkerState,
    endpoint: Option<EndpointCap>,
    lease: Option<LeaseWindow>,
    mode: WorkerMode,
    sequence: u64,
    pressure: PressureLevel,
}

impl WorkerLoop {
    /// Create a heartbeat worker loop.
    pub fn heartbeat(identity: WorkerIdentity, interval_ms: u64) -> Result<Self, WorkerLoopError> {
        if !identity.valid() {
            return Err(WorkerLoopError::InvalidIdentity);
        }
        if identity.role != WorkerRole::Heartbeat {
            return Err(WorkerLoopError::RoleMismatch);
        }
        if interval_ms == 0 {
            return Err(WorkerLoopError::InvalidHeartbeatInterval);
        }
        Ok(Self::new(
            identity,
            WorkerMode::Heartbeat {
                interval_ms,
                next_due_ms: 0,
                tick: 0,
            },
        ))
    }

    /// Create a GPU receipt-only worker loop.
    pub fn gpu_receipts(identity: WorkerIdentity) -> Result<Self, WorkerLoopError> {
        if !identity.valid() {
            return Err(WorkerLoopError::InvalidIdentity);
        }
        if identity.role != WorkerRole::Gpu {
            return Err(WorkerLoopError::RoleMismatch);
        }
        Ok(Self::new(
            identity,
            WorkerMode::Receipt {
                kind: ReceiptKind::GpuControl,
            },
        ))
    }

    /// Create a LoRA receipt-only worker loop.
    pub fn lora_receipts(identity: WorkerIdentity) -> Result<Self, WorkerLoopError> {
        if !identity.valid() {
            return Err(WorkerLoopError::InvalidIdentity);
        }
        if identity.role != WorkerRole::Lora {
            return Err(WorkerLoopError::RoleMismatch);
        }
        Ok(Self::new(
            identity,
            WorkerMode::Receipt {
                kind: ReceiptKind::LoraControl,
            },
        ))
    }

    fn new(identity: WorkerIdentity, mode: WorkerMode) -> Self {
        Self {
            identity,
            state: WorkerState::Detached,
            endpoint: None,
            lease: None,
            mode,
            sequence: 0,
            pressure: PressureLevel::Nominal,
        }
    }

    /// Return the identity bound to this worker loop.
    #[must_use]
    pub const fn identity(&self) -> WorkerIdentity {
        self.identity
    }

    /// Return the current worker state.
    #[must_use]
    pub const fn state(&self) -> WorkerState {
        self.state
    }

    /// Return the current pressure level.
    #[must_use]
    pub const fn pressure(&self) -> PressureLevel {
        self.pressure
    }

    /// Execute one bounded worker turn.
    pub fn step(&mut self, event: WorkerEvent) -> Result<StepOutcome, WorkerLoopError> {
        match event {
            WorkerEvent::Attach(request) => self.attach(request),
            other => {
                if self.state.is_terminal() {
                    return Err(WorkerLoopError::TerminalState);
                }
                if let Some(outcome) = self.expire_if_needed(other.now_ms())? {
                    return Ok(outcome);
                }
                match other {
                    WorkerEvent::Poll { now_ms } => self.poll(now_ms),
                    WorkerEvent::Notify(notification) => self.notify(notification),
                    WorkerEvent::Receipt(request) => self.receipt(request),
                    WorkerEvent::Attach(_) => unreachable!(),
                }
            }
        }
    }

    /// Execute at most `max_turns` events from `events`.
    pub fn run_bounded(&mut self, events: &[WorkerEvent], max_turns: usize) -> BoundedRun {
        let mut processed = 0usize;
        let mut emitted = 0usize;
        let mut error = None;
        for event in events.iter().take(max_turns) {
            match self.step(*event) {
                Ok(outcome) => {
                    processed = processed.saturating_add(1);
                    if outcome.output.is_some() {
                        emitted = emitted.saturating_add(1);
                    }
                    if self.state.is_terminal() {
                        break;
                    }
                }
                Err(err) => {
                    error = Some(err);
                    break;
                }
            }
        }
        BoundedRun {
            processed,
            emitted,
            terminal: self.state.is_terminal(),
            error,
        }
    }

    fn attach(&mut self, request: AttachRequest) -> Result<StepOutcome, WorkerLoopError> {
        match self.state {
            WorkerState::Detached => {}
            state if state.is_terminal() => return Err(WorkerLoopError::TerminalState),
            WorkerState::Attached => return Err(WorkerLoopError::AlreadyAttached),
            WorkerState::Revoked | WorkerState::Shutdown | WorkerState::LeaseExpired => {
                return Err(WorkerLoopError::TerminalState);
            }
        }
        if !request.endpoint.badge().matches_identity(self.identity) {
            return Err(WorkerLoopError::BadgeMismatch);
        }
        let lease = LeaseWindow::new(request.now_ms, request.lease_ttl_ms)?;
        self.endpoint = Some(request.endpoint);
        self.lease = Some(lease);
        self.state = WorkerState::Attached;
        if let WorkerMode::Heartbeat {
            ref mut next_due_ms,
            ..
        } = self.mode
        {
            *next_due_ms = request.now_ms;
        }
        let output = self.emit_lifecycle(request.now_ms, LifecycleEvent::Attached)?;
        Ok(StepOutcome {
            progress: WorkerProgress::Attached,
            output: Some(output),
        })
    }

    fn poll(&mut self, now_ms: u64) -> Result<StepOutcome, WorkerLoopError> {
        self.require_attached()?;
        match self.mode {
            WorkerMode::Heartbeat {
                interval_ms,
                ref mut next_due_ms,
                ref mut tick,
            } => {
                if now_ms < *next_due_ms {
                    return Ok(StepOutcome {
                        progress: WorkerProgress::Idle,
                        output: None,
                    });
                }
                let record = TelemetryRecord::Heartbeat {
                    now_ms,
                    tick: *tick,
                };
                *tick = tick.saturating_add(1);
                *next_due_ms = now_ms.saturating_add(interval_ms);
                let output = self.emit(InvocationKind::Telemetry(record))?;
                Ok(StepOutcome {
                    progress: WorkerProgress::Emitted,
                    output: Some(output),
                })
            }
            WorkerMode::Receipt { .. } => Ok(StepOutcome {
                progress: WorkerProgress::Idle,
                output: None,
            }),
        }
    }

    fn notify(&mut self, notification: WorkerNotification) -> Result<StepOutcome, WorkerLoopError> {
        self.require_attached()?;
        let now_ms = notification.now_ms();
        let event = match notification {
            WorkerNotification::Revoke { .. } => LifecycleEvent::Revoked,
            WorkerNotification::Shutdown { .. } => LifecycleEvent::Shutdown,
            WorkerNotification::Lease { ttl_ms, .. } => {
                self.lease = Some(LeaseWindow::new(now_ms, ttl_ms)?);
                LifecycleEvent::LeaseRenewed
            }
            WorkerNotification::Pressure { level, .. } => {
                self.pressure = level;
                LifecycleEvent::Pressure(level)
            }
        };
        let output = self.emit_lifecycle(now_ms, event)?;
        match event {
            LifecycleEvent::Revoked => self.finish_terminal(WorkerState::Revoked),
            LifecycleEvent::Shutdown => self.finish_terminal(WorkerState::Shutdown),
            _ => {}
        }
        Ok(StepOutcome {
            progress: if self.state.is_terminal() {
                WorkerProgress::Terminal
            } else {
                WorkerProgress::Lifecycle
            },
            output: Some(output),
        })
    }

    fn receipt(&mut self, request: ReceiptRequest) -> Result<StepOutcome, WorkerLoopError> {
        self.require_attached()?;
        let expected = self
            .mode
            .receipt_kind()
            .ok_or(WorkerLoopError::ReceiptMismatch)?;
        if request.kind != expected {
            return Err(WorkerLoopError::ReceiptMismatch);
        }
        let sequence = self.next_sequence();
        let record = ReceiptRecord {
            now_ms: request.now_ms,
            sequence,
            receipt_id: request.receipt_id,
            kind: request.kind,
        };
        let output = self.emit_with_sequence(sequence, InvocationKind::Receipt(record))?;
        Ok(StepOutcome {
            progress: WorkerProgress::Emitted,
            output: Some(output),
        })
    }

    fn expire_if_needed(&mut self, now_ms: u64) -> Result<Option<StepOutcome>, WorkerLoopError> {
        self.require_attached()?;
        let Some(lease) = self.lease else {
            return Err(WorkerLoopError::NotAttached);
        };
        if !lease.is_expired(now_ms) {
            return Ok(None);
        }
        let output = self.emit_lifecycle(now_ms, LifecycleEvent::LeaseExpired)?;
        self.finish_terminal(WorkerState::LeaseExpired);
        Ok(Some(StepOutcome {
            progress: WorkerProgress::Terminal,
            output: Some(output),
        }))
    }

    fn require_attached(&self) -> Result<(), WorkerLoopError> {
        match self.state {
            WorkerState::Attached => Ok(()),
            WorkerState::Detached => Err(WorkerLoopError::NotAttached),
            WorkerState::Revoked | WorkerState::Shutdown | WorkerState::LeaseExpired => {
                Err(WorkerLoopError::TerminalState)
            }
        }
    }

    fn emit_lifecycle(
        &mut self,
        now_ms: u64,
        event: LifecycleEvent,
    ) -> Result<EndpointInvocation, WorkerLoopError> {
        let sequence = self.next_sequence();
        let record = LifecycleRecord {
            now_ms,
            sequence,
            event,
        };
        self.emit_with_sequence(sequence, InvocationKind::Lifecycle(record))
    }

    fn emit(&mut self, kind: InvocationKind) -> Result<EndpointInvocation, WorkerLoopError> {
        let sequence = self.next_sequence();
        self.emit_with_sequence(sequence, kind)
    }

    fn emit_with_sequence(
        &self,
        sequence: u64,
        kind: InvocationKind,
    ) -> Result<EndpointInvocation, WorkerLoopError> {
        let endpoint = self.endpoint.ok_or(WorkerLoopError::NotAttached)?;
        Ok(EndpointInvocation {
            endpoint,
            badge: self.identity.badge_for(invocation_action(kind)),
            sequence,
            kind,
        })
    }

    fn next_sequence(&mut self) -> u64 {
        self.sequence = self.sequence.saturating_add(1);
        self.sequence
    }

    fn finish_terminal(&mut self, state: WorkerState) {
        self.state = state;
        self.endpoint = None;
        self.lease = None;
    }
}

fn invocation_action(kind: InvocationKind) -> WorkerEndpointAction {
    match kind {
        InvocationKind::Telemetry(_) => WorkerEndpointAction::Telemetry,
        InvocationKind::Receipt(_) => WorkerEndpointAction::Receipt,
        InvocationKind::Lifecycle(record) => match record.event {
            LifecycleEvent::Attached => WorkerEndpointAction::Attach,
            LifecycleEvent::LeaseRenewed | LifecycleEvent::LeaseExpired => {
                WorkerEndpointAction::Lease
            }
            LifecycleEvent::Revoked | LifecycleEvent::Shutdown => WorkerEndpointAction::Revoke,
            LifecycleEvent::Pressure(_) => WorkerEndpointAction::Telemetry,
        },
    }
}

