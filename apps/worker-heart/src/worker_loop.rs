//! Bounded worker-loop primitives shared by VM worker roles.

/// Default heartbeat cadence used by the no_std heartbeat worker loop.
pub const DEFAULT_HEARTBEAT_INTERVAL_MS: u64 = 1_000;
const BADGE_EPOCH_BITS: u8 = 8;
const BADGE_ATTACH_BASE: u64 = 0x260c_1000;
const BADGE_TELEMETRY_BASE: u64 = 0x260c_2000;
const BADGE_LEASE_BASE: u64 = 0x260c_3000;
const BADGE_RECEIPT_BASE: u64 = 0x260c_4000;
const BADGE_REVOKE_BASE: u64 = 0x260c_5000;

/// Worker roles that may own a bounded loop instance.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum WorkerRole {
    /// Heartbeat telemetry worker.
    Heartbeat = 1,
    /// GPU control receipt worker.
    Gpu = 2,
    /// LoRA control receipt worker.
    Lora = 3,
}

impl WorkerRole {
    const fn badge_code(self) -> u8 {
        self as u8
    }
}

/// Five-part Worker identity used by the bounded host compatibility model.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct WorkerIdentity {
    /// Role assigned to the worker.
    pub role: WorkerRole,
    /// Manifest-local Worker slot.
    pub slot: u32,
    /// Lease epoch associated with this worker authority.
    pub lease_epoch: u64,
    /// Generation of the root-owned supervisor instance.
    pub supervisor_generation: u64,
    /// Capability-bundle or endpoint-cap generation.
    pub cap_generation: u64,
}

impl WorkerIdentity {
    /// Create a worker identity.
    #[must_use]
    pub const fn new(
        role: WorkerRole,
        slot: u32,
        lease_epoch: u64,
        supervisor_generation: u64,
        cap_generation: u64,
    ) -> Self {
        Self {
            role,
            slot,
            lease_epoch,
            supervisor_generation,
            cap_generation,
        }
    }

    /// Return true when all generation-bearing identity components are present.
    #[must_use]
    pub const fn valid(self) -> bool {
        self.lease_epoch != 0 && self.supervisor_generation != 0 && self.cap_generation != 0
    }

    /// Return the deterministic attach badge expected on this worker's endpoint cap.
    #[must_use]
    pub const fn badge(self) -> WorkerBadge {
        self.badge_for(WorkerEndpointAction::Attach)
    }

    /// Return the deterministic badge for a worker endpoint action.
    #[must_use]
    pub const fn badge_for(self, action: WorkerEndpointAction) -> WorkerBadge {
        let role = (self.role.badge_code() as u64) << BADGE_EPOCH_BITS;
        let epoch = self.lease_epoch & ((1u64 << BADGE_EPOCH_BITS) - 1);
        WorkerBadge::from_raw(action.base().saturating_add(role | epoch))
    }
}

/// Worker endpoint-cap action classes generated by root-task.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WorkerEndpointAction {
    /// Attach the worker.
    Attach,
    /// Emit telemetry.
    Telemetry,
    /// Renew or expire a lease.
    Lease,
    /// Emit a control receipt.
    Receipt,
    /// Publish a revoke-sensitive event.
    Revoke,
}

impl WorkerEndpointAction {
    const fn base(self) -> u64 {
        match self {
            Self::Attach => BADGE_ATTACH_BASE,
            Self::Telemetry => BADGE_TELEMETRY_BASE,
            Self::Lease => BADGE_LEASE_BASE,
            Self::Receipt => BADGE_RECEIPT_BASE,
            Self::Revoke => BADGE_REVOKE_BASE,
        }
    }
}

/// Badged endpoint identity supplied by root-task.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct WorkerBadge {
    raw: u64,
}

impl WorkerBadge {
    /// Build a badge from its raw seL4 badge value.
    #[must_use]
    pub const fn from_raw(raw: u64) -> Self {
        Self { raw }
    }

    /// Return the raw badge value.
    #[must_use]
    pub const fn raw(self) -> u64 {
        self.raw
    }

    /// Return true when the badge matches the supplied identity.
    #[must_use]
    pub const fn matches_identity(self, identity: WorkerIdentity) -> bool {
        self.raw == identity.badge().raw()
    }
}

/// Endpoint capability visible to a worker loop.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct EndpointCap {
    cptr: u64,
    badge: WorkerBadge,
}

impl EndpointCap {
    /// Create an endpoint capability model with a non-zero CPtr and badge.
    pub const fn new(cptr: u64, badge: WorkerBadge) -> Result<Self, WorkerLoopError> {
        if cptr == 0 {
            return Err(WorkerLoopError::InvalidEndpointCap);
        }
        if badge.raw() == 0 {
            return Err(WorkerLoopError::InvalidBadge);
        }
        Ok(Self { cptr, badge })
    }

    /// Return the endpoint CPtr.
    #[must_use]
    pub const fn cptr(self) -> u64 {
        self.cptr
    }

    /// Return the endpoint badge.
    #[must_use]
    pub const fn badge(self) -> WorkerBadge {
        self.badge
    }
}

/// Attach request delivered to a detached worker.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AttachRequest {
    /// Endpoint cap used for worker receipts and telemetry.
    pub endpoint: EndpointCap,
    /// Monotonic time when attach was admitted.
    pub now_ms: u64,
    /// Lease time-to-live for this worker authority.
    pub lease_ttl_ms: u64,
}

/// Pressure level reported by root-task notifications.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PressureLevel {
    /// Normal operation.
    Nominal,
    /// Nonessential output should be reduced.
    High,
    /// Only essential receipts should be attempted.
    Overload,
}

/// Lifecycle notifications delivered to an attached worker.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WorkerNotification {
    /// Revoke the current endpoint authority.
    Revoke {
        /// Monotonic event time.
        now_ms: u64,
    },
    /// Shut the worker down gracefully.
    Shutdown {
        /// Monotonic event time.
        now_ms: u64,
    },
    /// Renew the active lease.
    Lease {
        /// Monotonic renewal time.
        now_ms: u64,
        /// New lease time-to-live.
        ttl_ms: u64,
    },
    /// Publish pressure state.
    Pressure {
        /// Monotonic event time.
        now_ms: u64,
        /// Current pressure level.
        level: PressureLevel,
    },
}

impl WorkerNotification {
    fn now_ms(self) -> u64 {
        match self {
            Self::Revoke { now_ms }
            | Self::Shutdown { now_ms }
            | Self::Lease { now_ms, .. }
            | Self::Pressure { now_ms, .. } => now_ms,
        }
    }
}

/// Receipt classes emitted by control-only VM workers.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReceiptKind {
    /// Heartbeat telemetry receipt.
    Heartbeat,
    /// GPU control receipt; hardware execution remains host-side.
    GpuControl,
    /// LoRA control receipt; training execution remains host-side.
    LoraControl,
}

/// Receipt request admitted by the worker loop.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ReceiptRequest {
    /// Monotonic request time.
    pub now_ms: u64,
    /// Caller-supplied receipt identifier.
    pub receipt_id: u64,
    /// Receipt class being requested.
    pub kind: ReceiptKind,
}

/// Event consumed by a worker loop turn.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WorkerEvent {
    /// Attach a detached worker to a badged endpoint.
    Attach(AttachRequest),
    /// Poll the worker for bounded progress.
    Poll {
        /// Monotonic poll time.
        now_ms: u64,
    },
    /// Deliver a lifecycle notification.
    Notify(WorkerNotification),
    /// Request a receipt emission.
    Receipt(ReceiptRequest),
}

impl WorkerEvent {
    fn now_ms(self) -> u64 {
        match self {
            Self::Attach(request) => request.now_ms,
            Self::Poll { now_ms } => now_ms,
            Self::Notify(notification) => notification.now_ms(),
            Self::Receipt(request) => request.now_ms,
        }
    }
}

/// Worker lifecycle state.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WorkerState {
    /// No endpoint authority has been attached.
    Detached,
    /// Endpoint authority is active.
    Attached,
    /// Authority was explicitly revoked.
    Revoked,
    /// Worker received shutdown.
    Shutdown,
    /// Active lease expired.
    LeaseExpired,
}

impl WorkerState {
    /// Return true when no further telemetry or receipts may be emitted.
    #[must_use]
    pub const fn is_terminal(self) -> bool {
        matches!(self, Self::Revoked | Self::Shutdown | Self::LeaseExpired)
    }
}

/// Lifecycle events emitted through the endpoint.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LifecycleEvent {
    /// Attach was accepted.
    Attached,
    /// Active lease was renewed.
    LeaseRenewed,
    /// Active lease expired.
    LeaseExpired,
    /// Authority was revoked.
    Revoked,
    /// Shutdown was requested.
    Shutdown,
    /// Pressure state changed.
    Pressure(PressureLevel),
}

