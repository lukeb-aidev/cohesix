use anyhow::{bail, Context, Result};
use clap::Parser;
use std::path::{Path, PathBuf};

#[derive(Parser)]
struct Args {
    /// Existing target source manifest; target and driver selections are retained.
    #[arg(long)]
    base: PathBuf,
    /// Generated TOML consumed by every subsequent build and compiler invocation.
    #[arg(long)]
    out: PathBuf,
    /// Deployment public Ed25519 key below the output directory, never a published fixture key.
    #[arg(long)]
    verification_key: PathBuf,
    /// Independently promoted authority-owner epoch.
    #[arg(long)]
    writer_epoch: u64,
}

fn bind_public_key_to_output(
    manifest: &mut coh_rtc::ir::Manifest,
    verification_key: &Path,
    output_dir: &Path,
) -> Result<()> {
    let output_dir = output_dir
        .canonicalize()
        .context("resolve profile output directory")?;
    let verification_key = verification_key
        .canonicalize()
        .context("resolve public verification key")?;
    let relative = verification_key.strip_prefix(&output_dir).context(
        "public verification key must be below the profile output directory for portable builds",
    )?;
    let relative = relative
        .to_str()
        .context("public verification key path must be UTF-8")?;
    if relative.is_empty() {
        bail!("public verification key must name a file below the profile output directory");
    }
    manifest
        .cas
        .signing
        .as_mut()
        .context("production profile requires CAS signing")?
        .verification_key_path = Some(relative.to_owned());
    manifest.validate_with_base(Some(&output_dir))?;
    Ok(())
}

fn main() -> Result<()> {
    let args = Args::parse();
    let manifest = coh_rtc::ir::load_manifest(&args.base)?;
    let mut manifest =
        coh_rtc::authority::release_a(manifest, &args.verification_key, args.writer_epoch)?;
    let output_dir = args
        .out
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    std::fs::create_dir_all(output_dir)?;
    bind_public_key_to_output(&mut manifest, &args.verification_key, output_dir)?;
    let body = toml::to_string_pretty(&manifest).context("serialize production manifest")?;
    let header = "# Author: Lukas Bower\n# Purpose: Bind the selected production target to deployment secret references.\n# Copyright 2026 Lukas Bower\n# Generated by coh-rtc-authority-profile. DO NOT EDIT BY HAND.\n";
    std::fs::write(&args.out, format!("{header}{body}"))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn public_key_reference_survives_profile_relocation() {
        let temporary = tempfile::TempDir::new().expect("temporary profile");
        let first = temporary.path().join("first");
        let key = first.join("resources/keys/cas_verification_key.hex");
        std::fs::create_dir_all(key.parent().expect("key directory")).expect("key directory");
        let public = ed25519_dalek::SigningKey::from_bytes(&[42; 32]).verifying_key();
        std::fs::write(&key, hex::encode(public.to_bytes())).expect("public key");
        let base = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../configs/root_task.toml");
        let source = coh_rtc::ir::load_manifest(&base).expect("source manifest");
        let mut profile = coh_rtc::authority::release_a(source, &key, 1).expect("profile");
        bind_public_key_to_output(&mut profile, &key, &first).expect("portable key");
        assert_eq!(
            profile
                .cas
                .signing
                .as_ref()
                .expect("CAS signing")
                .verification_key_path
                .as_deref(),
            Some("resources/keys/cas_verification_key.hex"),
        );
        let serialized = toml::to_string_pretty(&profile).expect("serialize profile");
        let second = temporary.path().join("second");
        std::fs::rename(&first, &second).expect("relocate profile directory");
        std::fs::write(second.join("production.toml"), serialized).expect("relocated profile");
        coh_rtc::ir::load_manifest(&second.join("production.toml"))
            .expect("relocated profile remains valid");
    }

    #[test]
    fn public_key_outside_profile_directory_is_refused() {
        let temporary = tempfile::TempDir::new().expect("temporary profile");
        let output_dir = temporary.path().join("output");
        std::fs::create_dir(&output_dir).expect("output directory");
        let key = temporary.path().join("verification.hex");
        std::fs::write(&key, "public-key-shape-only").expect("public key");
        let base = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../configs/root_task.toml");
        let source = coh_rtc::ir::load_manifest(&base).expect("source manifest");
        let mut profile = coh_rtc::authority::release_a(source, &key, 1).expect("profile");
        let error = bind_public_key_to_output(&mut profile, &key, &output_dir)
            .expect_err("out-of-tree key must be refused");
        assert!(error
            .to_string()
            .contains("below the profile output directory"));
    }
}
