use anyhow::{Context, Result};
use clap::Parser;
use std::path::PathBuf;

#[derive(Parser)]
struct Args {
    /// Existing target source manifest; target and driver selections are retained.
    #[arg(long)]
    base: PathBuf,
    /// Generated TOML consumed by every subsequent build and compiler invocation.
    #[arg(long)]
    out: PathBuf,
    /// Deployment public Ed25519 verification key, never a published fixture key.
    #[arg(long)]
    verification_key: PathBuf,
    /// Independently promoted authority-owner epoch.
    #[arg(long)]
    writer_epoch: u64,
}

fn main() -> Result<()> {
    let args = Args::parse();
    let manifest = coh_rtc::ir::load_manifest(&args.base)?;
    let manifest =
        coh_rtc::authority::release_a(manifest, &args.verification_key, args.writer_epoch)?;
    manifest.validate_with_base(args.base.parent())?;
    let body = toml::to_string_pretty(&manifest).context("serialize Release A manifest")?;
    let header = "# Author: Lukas Bower\n# Purpose: Bind the selected Release A target to deployment secret references.\n# Copyright 2026 Lukas Bower\n# Generated by coh-rtc-authority-profile. DO NOT EDIT BY HAND.\n";
    if let Some(parent) = args.out.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&args.out, format!("{header}{body}"))?;
    Ok(())
}
