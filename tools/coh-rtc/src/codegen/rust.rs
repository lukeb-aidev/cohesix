fn ticket_key_literal(secret: &str) -> Result<String> {
    let key = cohesix_ticket::TicketKey::from_secret(secret).to_bytes();
    let mut literal = String::from("[");
    for (idx, byte) in key.iter().copied().enumerate() {
        if idx > 0 {
            literal.push_str(", ");
        }
        write!(literal, "0x{byte:02x}")?;
    }
    literal.push(']');
    Ok(literal)
}

